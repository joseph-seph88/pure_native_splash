import 'dart:convert';

import 'package:file/memory.dart';
import 'package:pure_native_splash/src/config.dart';
import 'package:pure_native_splash/src/ios_writer.dart';
import 'package:pure_native_splash/src/stock_templates.dart';
import 'package:test/test.dart';

void main() {
  group('IosSplashWriter.hasIosPlatform', () {
    test('is false when ios/ is missing', () {
      final fs = MemoryFileSystem();
      fs.directory('/app').createSync();
      expect(IosSplashWriter(fs, '/app').hasIosPlatform, isFalse);
    });

    test('is true when ios/ exists', () {
      final fs = MemoryFileSystem();
      fs.directory('/app/ios').createSync(recursive: true);
      expect(IosSplashWriter(fs, '/app').hasIosPlatform, isTrue);
    });
  });

  group('IosSplashWriter.write', () {
    late MemoryFileSystem fs;
    const projectRoot = '/app';
    const runnerDir = '/app/ios/Runner';

    setUp(() {
      fs = MemoryFileSystem();
      fs.directory('$projectRoot/ios/Runner').createSync(recursive: true);
    });

    test('writes exactly 2 files at the expected paths', () {
      final writer = IosSplashWriter(fs, projectRoot);
      final written = writer.write(
        const PureNativeSplashConfig(color: '#FFFFFF', colorDark: '#000000'),
      );

      expect(written, [
        '$runnerDir/Base.lproj/LaunchScreen.storyboard',
        '$runnerDir/Assets.xcassets/LaunchBackground.colorset/Contents.json',
      ]);
      for (final path in written) {
        expect(fs.file(path).existsSync(), isTrue, reason: path);
      }
    });

    test(
      'storyboard references the LaunchBackground asset-catalog color by '
      'name instead of a literal color',
      () {
        final writer = IosSplashWriter(fs, projectRoot);
        writer.write(
          const PureNativeSplashConfig(
            color: '#FFFFFF',
            colorDark: '#000000',
          ),
        );

        final content = fs
            .file('$runnerDir/Base.lproj/LaunchScreen.storyboard')
            .readAsStringSync();
        expect(
          content,
          contains('<color key="backgroundColor" name="LaunchBackground"/>'),
        );
        expect(content, isNot(contains('customColorSpace="sRGB"')));
        expect(content, contains('GENERATED by pure_native_splash'));
      },
    );

    test(
      'storyboard has no LaunchImage reference, so leftover imageset '
      'contents (e.g. from flutter_native_splash) cannot appear',
      () {
        final writer = IosSplashWriter(fs, projectRoot);
        writer.write(
          const PureNativeSplashConfig(
            color: '#FFFFFF',
            colorDark: '#000000',
          ),
        );

        final content = fs
            .file('$runnerDir/Base.lproj/LaunchScreen.storyboard')
            .readAsStringSync();
        expect(content, isNot(contains('LaunchImage')));
        expect(content, isNot(contains('<imageView')));
      },
    );

    test(
      'colorset Contents.json encodes light and dark colors as sRGB float '
      'components',
      () {
        final writer = IosSplashWriter(fs, projectRoot);
        writer.write(
          const PureNativeSplashConfig(
            color: '#3366FF',
            colorDark: '#111111',
          ),
        );

        final content = fs
            .file(
              '$runnerDir/Assets.xcassets/LaunchBackground.colorset/Contents.json',
            )
            .readAsStringSync();
        final decoded = jsonDecode(content) as Map<String, Object?>;

        final colors = decoded['colors']! as List<Object?>;
        expect(colors, hasLength(2));

        final light = colors[0]! as Map<String, Object?>;
        expect(light.containsKey('appearances'), isFalse);
        expect((light['color']! as Map)['components'], {
          'red': '0.200',
          'green': '0.400',
          'blue': '1.000',
          'alpha': '1.000',
        });

        final dark = colors[1]! as Map<String, Object?>;
        expect(dark['appearances'], [
          {'appearance': 'luminosity', 'value': 'dark'},
        ]);
        expect((dark['color']! as Map)['components'], {
          'red': '0.067',
          'green': '0.067',
          'blue': '0.067',
          'alpha': '1.000',
        });

        expect(decoded['info'], {
          'author': 'pure_native_splash',
          'version': 1,
        });
      },
    );

    test('re-running overwrites previous contents instead of appending', () {
      final writer = IosSplashWriter(fs, projectRoot);
      writer.write(
        const PureNativeSplashConfig(color: '#111111', colorDark: '#222222'),
      );
      writer.write(
        const PureNativeSplashConfig(color: '#FFFFFF', colorDark: '#000000'),
      );

      final content = fs
          .file(
            '$runnerDir/Assets.xcassets/LaunchBackground.colorset/Contents.json',
          )
          .readAsStringSync();
      expect(content, contains('"1.000"'));
      expect(content, isNot(contains('0.067')));
    });
  });

  group('IosSplashWriter.remove', () {
    late MemoryFileSystem fs;
    const projectRoot = '/app';
    const runnerDir = '/app/ios/Runner';
    const config = PureNativeSplashConfig(
      color: '#3366FF',
      colorDark: '#111111',
    );

    setUp(() {
      fs = MemoryFileSystem();
      fs.directory('$projectRoot/ios/Runner').createSync(recursive: true);
    });

    test(
      'after create, restores the stock storyboard and deletes the colorset',
      () {
        final writer = IosSplashWriter(fs, projectRoot);
        writer.write(config);

        final result = writer.remove();

        final storyboard = fs
            .file('$runnerDir/Base.lproj/LaunchScreen.storyboard')
            .readAsStringSync();
        expect(
          storyboard,
          stockLaunchScreenStoryboard,
          reason: 'must be byte-identical to the flutter create template',
        );
        expect(
          fs
              .directory('$runnerDir/Assets.xcassets/LaunchBackground.colorset')
              .existsSync(),
          isFalse,
        );
        expect(result.restored, hasLength(1));
        expect(result.deleted, hasLength(1));
        expect(result.skipped, isEmpty);
      },
    );

    test('skips a hand-written storyboard and a foreign colorset', () {
      final storyboard = fs.file(
        '$runnerDir/Base.lproj/LaunchScreen.storyboard',
      );
      storyboard.createSync(recursive: true);
      storyboard.writeAsStringSync('<document>custom</document>');
      final contents = fs.file(
        '$runnerDir/Assets.xcassets/LaunchBackground.colorset/Contents.json',
      );
      contents.createSync(recursive: true);
      contents.writeAsStringSync('{"info": {"author": "xcode"}}');

      final result = IosSplashWriter(fs, projectRoot).remove();

      expect(storyboard.readAsStringSync(), contains('custom'));
      expect(contents.existsSync(), isTrue);
      expect(result.skipped, hasLength(2));
      expect(result.restored, isEmpty);
      expect(result.deleted, isEmpty);
    });

    test('is a no-op when create never ran', () {
      final result = IosSplashWriter(fs, projectRoot).remove();

      expect(result.restored, isEmpty);
      expect(result.deleted, isEmpty);
      expect(result.skipped, isEmpty);
    });

    test('running twice reports nothing the second time', () {
      final writer = IosSplashWriter(fs, projectRoot);
      writer.write(config);
      writer.remove();

      final result = writer.remove();

      expect(result.restored, isEmpty);
      expect(result.deleted, isEmpty);
      expect(result.skipped, isEmpty);
    });

    test('still owns its colorset after JSON reformatting', () {
      final contents = fs.file(
        '$runnerDir/Assets.xcassets/LaunchBackground.colorset/Contents.json',
      );
      contents.createSync(recursive: true);
      contents.writeAsStringSync(
        '{"colors":[],"info":{"version":1,"author":"pure_native_splash"}}',
      );

      final result = IosSplashWriter(fs, projectRoot).remove();

      expect(contents.existsSync(), isFalse);
      expect(result.deleted, hasLength(1));
      expect(result.skipped, isEmpty);
    });

    test('skips a colorset whose contents are not valid JSON', () {
      final contents = fs.file(
        '$runnerDir/Assets.xcassets/LaunchBackground.colorset/Contents.json',
      );
      contents.createSync(recursive: true);
      contents.writeAsStringSync('not json');

      final result = IosSplashWriter(fs, projectRoot).remove();

      expect(contents.existsSync(), isTrue);
      expect(result.skipped, hasLength(1));
    });
  });
}
